def word_match_score(text):
    """Fraction des mots du texte qui sont des mots anglais reconnus.
    1.0 = tous les mots sont reconnus, 0.0 = aucun. Beaucoup plus
    décisif que l'analyse de fréquence sur un texte court."""
    words = [w.strip('.,!?;:"\'()') for w in text.upper().split()]
    words = [w for w in words if w]
    if not words:
        return 0.0
    recognized = sum(1 for w in words if w in COMMON_WORDS)
    return recognized / len(words)


def chi_squared_score(text):
    """Mesure l'écart entre les fréquences de lettres du texte et
    celles attendues en anglais. Plus le score est bas, plus le texte
    ressemble à du vrai anglais."""
    text = text.upper()
    letters = [c for c in text if c.isalpha()]
    n = len(letters)
    if n == 0:
        return float('inf')

    counts = {letter: 0 for letter in ENGLISH_FREQ}
    for c in letters:
        counts[c] += 1

    score = 0.0
    for letter, expected_pct in ENGLISH_FREQ.items():
        observed = counts[letter]
        expected = expected_pct / 100 * n
        if expected > 0:
            score += (observed - expected) ** 2 / expected
    return score


def index_of_coincidence(letters):
    """Mesure la probabilité que deux lettres prises au hasard dans le
    texte soient identiques. Un vrai texte anglais tourne autour de
    0.065-0.070 ; un texte chiffré par Vigenère avec une longueur de
    clé erronée ressemble plus à du hasard pur (~0.038)."""
    n = len(letters)
    if n < 2:
        return 0.0
    counts = {}
    for c in letters:
        counts[c] = counts.get(c, 0) + 1
    total = sum(c * (c - 1) for c in counts.values())
    return total / (n * (n - 1))


def find_key_length(ciphertext, max_len=20):
    """Teste chaque longueur de clé candidate : on découpe le texte en
    `length` colonnes (une par position de la clé) et on calcule
    l'indice de coïncidence moyen de ces colonnes. La bonne longueur
    de clé donne des colonnes qui ressemblent chacune à un simple
    décalage de César sur du vrai anglais -> IC plus élevé."""
    letters_only = [c.upper() for c in ciphertext if c.isalpha()]

    best_length = 1
    best_avg_ic = 0.0
    scores = []

    for length in range(1, max_len + 1):
        columns = [letters_only[i::length] for i in range(length)]
        ics = [index_of_coincidence(col) for col in columns if len(col) > 1]
        if not ics:
            continue
        avg_ic = sum(ics) / len(ics)
        scores.append((length, avg_ic))
        if avg_ic > best_avg_ic:
            best_avg_ic = avg_ic
            best_length = length

    return best_length, scores


def crack_column_shift(column_letters):
    """Applique la même logique que le cassage d'un César simple sur
    une seule colonne : teste les 26 décalages, garde celui dont la
    distribution de lettres ressemble le plus à de l'anglais."""
    best_shift = 0
    best_score = float('inf')
    for shift in range(26):
        candidate = decrypt_shift(''.join(column_letters), shift)
        score = chi_squared_score(candidate)
        if score < best_score:
            best_score = score
            best_shift = shift
    return best_shift


def crack_key_for_length(ciphertext, key_length):
    """Déduit une clé en cassant chaque colonne séparément, pour une
    longueur de clé donnée."""
    letters_only = [c.upper() for c in ciphertext if c.isalpha()]
    columns = [letters_only[i::key_length] for i in range(key_length)]
    key = ''
    for col in columns:
        shift = crack_column_shift(col)
        key += chr(shift + ord('A'))
    return key


EXHAUSTIVE_MAX_LEN = 4  # 26^4 = ~457 000 combinaisons : encore rapide a tester
# le brute-force exhaustif n'a de sens que sur un texte court, la ou
# l'analyse par colonne manque de donnees pour etre fiable. Sur un texte
# long, la methode par colonne suffit deja et est beaucoup plus rapide ;
# lancer l'exhaustif en plus serait juste une perte de temps.
SHORT_TEXT_THRESHOLD = 40  # en nombre de lettres


def brute_force_short_key(ciphertext, length):
    """Pour une longueur de clé courte, le découpage en colonnes n'a
    pas assez de lettres par colonne pour que l'analyse de fréquence
    soit fiable (ex: 'KEY' sur 10 lettres = 3-4 lettres par colonne).
    Dans ce cas, on brute-force directement toutes les clés possibles
    de cette longueur (26^length, encore gérable jusqu'à 4 caractères)
    et on garde celle qui donne le plus de vrais mots reconnus."""
    import itertools

    best_key = None
    best_plaintext = None
    best_word_score = -1.0
    best_chi_score = float('inf')

    alphabet = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ'
    for combo in itertools.product(alphabet, repeat=length):
        key = ''.join(combo)
        plaintext = decrypt_vigenere(ciphertext, key)
        word_score = word_match_score(plaintext)
        chi_score = chi_squared_score(plaintext)
        better = (
            word_score > best_word_score
            or (word_score == best_word_score and chi_score < best_chi_score)
        )
        if better:
            best_word_score = word_score
            best_chi_score = chi_score
            best_key = key
            best_plaintext = plaintext

    return best_key, best_plaintext, best_word_score, best_chi_score


def crack_vigenere(ciphertext, max_key_len=20):
    """Cryptanalyse complète, en silence. Le script teste chaque
    longueur de clé candidate et casse vraiment la clé pour chacune,
    puis note chaque résultat sur deux critères :

    1. word_match_score — la fraction de vrais mots anglais reconnus.
       C'est le critère principal : décisif même sur un texte très
       court ("HELLO WORLD" se reconnaît direct), là où l'analyse de
       fréquence pure a besoin de volume pour être fiable.
    2. chi_squared_score — sert de filet de sécurité / départage
       quand deux candidats reconnaissent le même nombre de mots (ou
       zéro, si le texte n'a pas d'espaces par exemple).

    Seul le meilleur résultat global est retourné."""
    letters_only = [c.upper() for c in ciphertext if c.isalpha()]
    n_letters = len(letters_only)
    # une clé plus longue que la moitié du texte n'a pas de sens a tester
    max_len_to_try = max(1, min(max_key_len, n_letters // 2 or 1))

    best_key = None
    best_plaintext = None
    best_word_score = -1.0
    best_chi_score = float('inf')

    for length in range(1, max_len_to_try + 1):
        candidates = []

        # methode 1 : deduction colonne par colonne (fiable sur texte long)
        key_col = crack_key_for_length(ciphertext, length)
        pt_col = decrypt_vigenere(ciphertext, key_col)
        candidates.append((key_col, pt_col, word_match_score(pt_col), chi_squared_score(pt_col)))

        # methode 2 : brute-force exhaustif de la cle (fiable sur texte court,
        # mais inutile et lent sur un texte assez long pour que la methode
        # par colonne soit deja fiable)
        if length <= EXHAUSTIVE_MAX_LEN and n_letters < SHORT_TEXT_THRESHOLD:
            key_bf, pt_bf, ws_bf, cs_bf = brute_force_short_key(ciphertext, length)
            candidates.append((key_bf, pt_bf, ws_bf, cs_bf))

        for key, plaintext, word_score, chi_score in candidates:
            better = (
                word_score > best_word_score
                or (word_score == best_word_score and chi_score < best_chi_score)
            )
            if better:
                best_word_score = word_score
                best_chi_score = chi_score
                best_key = key
                best_plaintext = plaintext

    return best_key, best_plaintext


