def decrypt_vigenere(text, key):
    """Décrypte un texte avec une clé Vigenère donnée."""
    result = []
    key = key.upper()
    key_index = 0
    for char in text:
        if char.isalpha():
            base = ord('A') if char.isupper() else ord('a')
            shift = ord(key[key_index % len(key)]) - ord('A')
            decoded = chr((ord(char) - base - shift) % 26 + base)
            result.append(decoded)
            key_index += 1  # on avance la clé seulement sur une vraie lettre
        else:
            result.append(char)  # espaces et ponctuation inchangés
    return ''.join(result)


def decrypt_shift(text, shift):
    """Décale chaque lettre vers l'arrière de `shift` positions
    (c'est un Vigenère avec une clé d'une seule lettre)."""
    result = []
    for char in text:
        if char.isalpha():
            base = ord('A') if char.isupper() else ord('a')
            decoded = chr((ord(char) - base - shift) % 26 + base)
            result.append(decoded)
        else:
            result.append(char)
    return ''.join(result)


